import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { parseEnv } from 'node:util';
let fileEnv = {};
try {
  fileEnv = parseEnv(await readFile('.env', 'utf8'));
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}
const apiKey = process.env.DEFAPI_API_KEY ?? fileEnv.DEFAPI_API_KEY ?? '';
const openaiApiKey = process.env.OPENAI_API_KEY ?? fileEnv.OPENAI_API_KEY ?? '';
const files = ['core', 'dom', 'logging', 'runtime', 'panel', 'tampermonkey'];
const code = await Promise.all(files.map(name => readFile(`src/${name}.js`, 'utf8')));
await mkdir('dist', { recursive: true });
await writeFile('dist/clickator.js', `/* Clickator • JEV 1.13 • generated by npm run build */\n(() => {\n'use strict';\n${code.map(s => s.replace(/^import .*;\r?\n/gm, '').replace(/^export /gm, '')).join('\n')}\nconst defaults = options => ({ apiKey: ${JSON.stringify(apiKey)}, openaiApiKey: ${JSON.stringify(openaiApiKey)}, ...options });\nif (!globalThis.Clickator) globalThis.Clickator = { mount: options => mount(defaults(options)), create: options => new Runner(defaults(options)), scan: () => scan(document).publicState, gmTransport, gmTabStore, build: ${JSON.stringify(new Date().toISOString())} };\nconsole.info("[Clickator build]", { build: globalThis.Clickator.build, textModel: TEXT_MODEL });\n})();\n`);
console.log('Built dist/clickator.js');
